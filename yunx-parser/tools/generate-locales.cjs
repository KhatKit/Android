// Explicit first-party locale inputs; generated XML is never an input.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
function parseStrings(xml, label) {
  const records = new Map();
  for (const m of xml.matchAll(/<string\s+name="([^"]+)"([^>]*)>([\s\S]*?)<\/string>/g)) {
    if (records.has(m[1])) throw Error(label + ": duplicate key " + m[1]);
    records.set(m[1], { name: m[1], attrs: m[2], body: m[3], xml: m[0] });
  }
  if (!records.size) throw Error(label + ": no strings");
  return records;
}
function signature(value) {
  return [...value.matchAll(/%(?:\d+\$)?[-#+ 0,(<]*\d*(?:\.\d+)?[a-zA-Z%]/g)]
    .map(m => m[0]).sort().join("|");
}
function tags(value) {
  return (value.match(/<[^>]+>/g) || []).join("|");
}
function validatePair(name, english, chinese) {
  if (typeof english !== "string" || !english.trim()) throw Error("Missing English translation: " + name);
  if (/[\u3400-\u9fff]/u.test(english)) throw Error("Untranslated Chinese in English: " + name);
  if (/\b(?:TODO|TBD|FIXME)\b/.test(english)) throw Error("Placeholder translation: " + name);
  if (signature(english) !== signature(chinese)) throw Error("Format parameter mismatch: " + name);
  if (tags(english) !== tags(chinese)) throw Error("Rich-text markup mismatch: " + name);
}
function androidXml(value) {
  // Preserve matching rich-text tags; escape only text nodes for XML and aapt.
  return value.split(/(<[^>]+>)/g).map(part => part.startsWith("<") ? part :
    part.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
      .replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/"/g, '\\"')
      .replace(/\n/g, "\\n").replace(/\t/g, "\\t"))
    .join("").replace(/^ /, "\\u0020").replace(/ $/, "\\u0020");
}
function document(lines) {
  return '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/generate-locales.cjs; edit tools/localization inputs. -->\n<resources>\n' + lines.join("\n") + "\n</resources>\n";
}
function buildResources() {
  const input = path.join(__dirname, "localization");
  const source = parseStrings(fs.readFileSync(path.join(input, "upstream-zh.xml"), "utf8"), "upstream-zh.xml");
  const english = JSON.parse(fs.readFileSync(path.join(input, "en.json"), "utf8"));
  const host = JSON.parse(fs.readFileSync(path.join(input, "host.json"), "utf8"));
  const missing = [...source.keys()].filter(key => !Object.hasOwn(english, key));
  const extra = Object.keys(english).filter(key => !source.has(key));
  if (missing.length || extra.length) throw Error("English map differs: missing=[" + missing + "]; extra=[" + extra + "]");
  const en = [], zh = [], hostEn = [], hostZh = [];
  for (const [name, entry] of source) {
    validatePair(name, english[name], entry.body);
    en.push('<string name="' + name + '"' + entry.attrs + '>' + androidXml(english[name]) + '</string>');
    zh.push(entry.xml);
  }
  for (const [name, pair] of Object.entries(host)) {
    if (!/^[a-z][a-z0-9_]*$/.test(name) || source.has(name) || !Array.isArray(pair) || pair.length !== 2 || typeof pair[1] !== "string" || !pair[1].trim()) throw Error("Invalid host pair: " + name);
    validatePair(name, pair[0], pair[1]);
    hostEn.push('<string name="' + name + '">' + androidXml(pair[0]) + '</string>');
    hostZh.push('<string name="' + name + '">' + androidXml(pair[1]) + '</string>');
  }
  return { source, host, outputs: {
    "src/main/res/values/yunx_strings.xml": document(en),
    "src/main/res/values-zh/yunx_strings.xml": document(zh),
    "src/main/res/values/yunx_host_strings.xml": document(hostEn),
    "src/main/res/values-zh/yunx_host_strings.xml": document(hostZh),
  }};
}
function generate(check = false, resourceSet = buildResources()) {
  for (const [relative, content] of Object.entries(resourceSet.outputs)) {
    const file = path.join(root, relative);
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) throw Error("Generated resource differs: " + relative);
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content);
    }
  }
  return resourceSet;
}
if (require.main === module) {
  try {
    if (process.argv.slice(2).some(arg => arg !== "--check")) throw Error("Usage: node tools/generate-locales.cjs [--check]");
    const result = generate(process.argv.includes("--check"));
    console.log(result.source.size + " upstream + " + Object.keys(result.host).length + " host keys; English / Simplified Chinese complete");
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = { parseStrings, signature, validatePair, buildResources, generate };
